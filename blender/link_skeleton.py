"""Adult Link's limb structure, as Ocarina of Time actually declares it.

Nothing here is from memory. The table is generated by `tools/parse_link_skeleton.py`
from assets extracted out of a retail ROM, which is why it carries joint positions and
real parents rather than a plausible-looking humanoid hierarchy:

  * the limb names and array order come from `assets/xml/objects/object_link_boy.xml`,
    which declares 21 limbs under `gLinkAdultSkel`, a Flex skeleton of LOD limbs;
  * the enum names come from the `PlayerLimb` enum in `include/player.h`;
  * the parents come from each limb's first-child and next-sibling indices in the
    extracted limb data, which is the only place the hierarchy exists;
  * `draws` is whether the limb has a display list. Exactly 18 do, which matches the
    `dListCount` of 18 in `gLinkAdultSkel` and matches Fast64's rule that the root,
    upper control and lower control bones are the only non-deform ones.

Two things in here are worth knowing before modelling against it, because both differ
from how a humanoid rig is normally put together:

  * UpperControl is a child of Root, not of Waist. The upper and lower halves of Link
    hang off the root in parallel, so bending the waist does not carry the arms.
  * The shoulders hang off UpperControl, not off Collar. Collar is a leaf that only
    draws geometry, so nothing is parented to it.

Joint positions are in the game's own units and in its own axis convention, where X
runs along the limb rather than sideways. They are recorded for reference and for the
cross-check below; they are not Blender coordinates and must not be used as such. The
usable rig comes from a Fast64 "Import Skeleton: Adult Link", which applies the rest
pose rotations Fast64 carries for this skeleton.
"""

from __future__ import annotations

# name, parent, draws a display list, joint position in game units (x, y, z)
LIMBS: list[tuple[str, str | None, bool, tuple[int, int, int]]] = [
    ("Root", None, False, (-57, 3377, 0)),
    ("Waist", "Root", True, (0, 0, 0)),
    ("LowerControl", "Waist", False, (945, 0, 0)),
    ("RightThigh", "LowerControl", True, (-399, 69, -249)),
    ("RightShin", "RightThigh", True, (1306, 0, 0)),
    ("RightFoot", "RightShin", True, (1256, 5, 11)),
    ("LeftThigh", "LowerControl", True, (-396, 76, 264)),
    ("LeftShin", "LeftThigh", True, (1304, 0, 0)),
    ("LeftFoot", "LeftShin", True, (1257, 6, 3)),
    ("UpperControl", "Root", False, (0, 21, -7)),
    ("Head", "UpperControl", True, (1392, -259, 0)),
    ("Hat", "Head", True, (-298, -700, 0)),
    ("Collar", "UpperControl", True, (0, 0, 0)),
    ("LeftShoulder", "UpperControl", True, (1039, -172, 680)),
    ("LeftForearm", "LeftShoulder", True, (919, 0, 0)),
    ("LeftHand", "LeftForearm", True, (754, 0, 0)),
    ("RightShoulder", "UpperControl", True, (1039, -173, -680)),
    ("RightForearm", "RightShoulder", True, (919, 0, 0)),
    ("RightHand", "RightForearm", True, (754, 0, 0)),
    ("Sheath", "UpperControl", True, (978, -692, 342)),
    ("Torso", "UpperControl", True, (0, 0, 0)),
]

NAMES = [name for name, _parent, _draws, _pos in LIMBS]
DEFORM = [name for name, _parent, draws, _pos in LIMBS if draws]
NON_DEFORM = [name for name, _parent, draws, _pos in LIMBS if not draws]
PARENT = {name: parent for name, parent, _draws, _pos in LIMBS}
JOINT_POS = {name: pos for name, _parent, _draws, pos in LIMBS}

assert len(LIMBS) == 21, "object_link_boy.xml declares exactly 21 limbs"
assert len(DEFORM) == 18, "gLinkAdultSkel declares dListCount 18"
assert NON_DEFORM == ["Root", "LowerControl", "UpperControl"], (
    "Fast64 requires root, upper control and lower control to be the only "
    "non-deform bones"
)
assert [n for n in NAMES if PARENT[n] is None] == ["Root"], "Root alone has no parent"
assert set(PARENT.values()) <= set(NAMES) | {None}, "every parent must be a known limb"


def verify_against_imported(armature_obj) -> list[str]:
    """Compare this table against a skeleton Fast64 imported from the decompilation.

    Returns a list of complaints; empty means the import agrees. Run it before trusting
    an export: the table is derived from one ROM version, and a mismatch means the
    model is weighted against a skeleton the game does not have.
    """
    problems: list[str] = []
    bones = {b.name: b for b in armature_obj.data.bones}

    for name, parent, draws, _pos in LIMBS:
        bone = bones.get(name)
        if bone is None:
            problems.append(f"imported skeleton has no bone named {name!r}")
            continue
        actual_parent = bone.parent.name if bone.parent else None
        if actual_parent != parent:
            problems.append(
                f"{name}: table says parent {parent!r}, import says {actual_parent!r}"
            )
        if bone.use_deform != draws:
            problems.append(
                f"{name}: table says deform={draws}, import says {bone.use_deform}"
            )

    extra = sorted(set(bones) - set(NAMES))
    if extra:
        problems.append(f"imported skeleton has bones the table does not: {extra}")
    return problems
